// Ported from Zekra (togo/cabrain mobile/plugins/with-gradle-jvmargs.js).
// Raises the Gradle daemon's heap and metaspace: the default 2 GiB / 512 MiB ran out of
// metaspace on the first full build.
//
// Build with JDK 17 (React Native's supported version), not Android Studio's bundled JDK 25.
// Under JDK 25, AGP's CMake configure step fails for react-native-screens, react-native-worklets
// and expo-updates, because the JVMs it spawns (prefab) print warnings to stderr — "restricted
// method in java.lang.System", "Windows job object … processor groups" — and AGP treats any
// stderr there as a failure. Those JVMs do not take Gradle's jvmargs, so it cannot be silenced
// from here; point JAVA_HOME at a JDK 17 instead (see mobile/README.md).
//
// android/ is generated by prebuild, so this lives in a config plugin rather than a hand edit.
const { withGradleProperties } = require('expo/config-plugins');

const JVM_ARGS = '-Xmx4096m -XX:MaxMetaspaceSize=1024m';

module.exports = function withGradleJvmArgs(config) {
  return withGradleProperties(config, (cfg) => {
    const props = cfg.modResults.filter((p) => !(p.type === 'property' && p.key === 'org.gradle.jvmargs'));
    props.push({ type: 'property', key: 'org.gradle.jvmargs', value: JVM_ARGS });
    cfg.modResults = props;
    return cfg;
  });
};
