-- Automation: browsers paired with a workspace, and the runs they were asked
-- to do (MH-61). Ported from fadymondy.com's internal/agents + internal/
-- automation, with the one structural difference that matters here: every row
-- belongs to a WORKSPACE, not to an account.
--
-- Every table carries workspace_id and is isolated by RLS (internal/db/post/20_rls.sql).
-- Links use composite foreign keys (workspace_id, x_id) -> x (workspace_id, id),
-- for the reason internal/db/schema/crm.sql gives: a foreign-key check runs as
-- the table owner and ignores RLS, so a single-column FK would let one
-- workspace point a row at another workspace's.
--
-- This system drives browsers that are already signed into someone's mail,
-- bank and work tools. Every control here fails CLOSED: an empty allow-list
-- allows nothing, and a paused workspace runs nothing.

-- One row per browser paired with this workspace. The row IS the browser's
-- identity: the extension holds only a token, and every run is attributed to
-- the browser that did it.
CREATE TABLE IF NOT EXISTS browser_agents (
    id                text        PRIMARY KEY DEFAULT gen_random_uuid()::text,
    workspace_id      text        NOT NULL,
    -- What the operator called it: "Fady — work laptop".
    name              text        NOT NULL,
    -- Stable per browser profile, generated by the extension on first run, so a
    -- reinstall is recognised as the same browser rather than a second one.
    fingerprint       text        NOT NULL DEFAULT '',
    platform          text        NOT NULL DEFAULT '',
    browser_version   text        NOT NULL DEFAULT '',
    extension_version text        NOT NULL DEFAULT '',
    -- offline | online. Liveness is really the socket; this is the last known
    -- value so a page can render without asking the hub.
    status            text        NOT NULL DEFAULT 'offline',
    last_seen_at      timestamptz NOT NULL DEFAULT now(),
    -- sha256 of the token, never the token. Same treatment as mcp_tokens.
    token_hash        text        NOT NULL,
    -- First few characters, in clear, so a list can name a token without being
    -- able to use it.
    token_prefix      text        NOT NULL DEFAULT '',
    -- The hosts this browser may be driven against. EMPTY ALLOWS NOTHING —
    -- a browser is useless until someone says where it may go, which is the
    -- safe direction for the mistake.
    allowed_hosts     text[]      NOT NULL DEFAULT '{}',
    revoked_at        timestamptz,
    created_by        text        NOT NULL,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    UNIQUE (workspace_id, id),
    -- The socket resolves a browser by token hash with no workspace in hand, so
    -- this has to be unique across the whole table: two browsers sharing a
    -- token would make "which browser did this" unanswerable.
    UNIQUE (token_hash)
);

CREATE INDEX IF NOT EXISTS browser_agents_workspace_idx ON browser_agents (workspace_id, created_at DESC);
CREATE INDEX IF NOT EXISTS browser_agents_fingerprint_idx ON browser_agents (workspace_id, fingerprint);

-- A pairing request: created by an extension that has no token yet, resolved by
-- a member approving it. The row holds no usable secret at rest — the code and
-- the poll token are stored hashed, and the minted token lives here only
-- between approval and the extension collecting it, then is blanked.
CREATE TABLE IF NOT EXISTS agent_pairings (
    id                text        PRIMARY KEY DEFAULT gen_random_uuid()::text,
    workspace_id      text        NOT NULL,
    -- sha256 of the short code the operator reads off the extension.
    code_hash         text        NOT NULL,
    -- sha256 of the poll token, which never leaves the extension. Polling uses
    -- THIS, not the code: the code is short and gets read aloud, and whoever
    -- overheard it could otherwise race the extension and collect the token.
    poll_hash         text        NOT NULL,
    fingerprint       text        NOT NULL DEFAULT '',
    platform          text        NOT NULL DEFAULT '',
    browser_version   text        NOT NULL DEFAULT '',
    extension_version text        NOT NULL DEFAULT '',
    -- What the extension suggests calling this browser. It comes from an
    -- unauthenticated caller, so it is shown as a suggestion and never trusted.
    requested_name    text        NOT NULL DEFAULT '',
    -- Advisory only, from the proxy header: it makes an unexpected request look
    -- unexpected. It is not proof of anything.
    ip                text        NOT NULL DEFAULT '',
    -- pending | approved | claimed | denied
    status            text        NOT NULL DEFAULT 'pending',
    agent_id          text,
    -- The minted token, readable exactly once by the extension that started
    -- this pairing, then blanked. Empty at every other moment in the row's life.
    token_once        text        NOT NULL DEFAULT '',
    expires_at        timestamptz NOT NULL,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    UNIQUE (workspace_id, id),
    -- Same reason as the token hash above: both lookups happen before any
    -- workspace is known.
    UNIQUE (code_hash),
    UNIQUE (poll_hash)
);

CREATE INDEX IF NOT EXISTS agent_pairings_sweep_idx ON agent_pairings (status, expires_at);

-- A run is the record of what a browser was asked to do and what came back. It
-- is what the page reads, what MCP hands to a model, and what someone looks at
-- when an automation quietly stopped working — so it keeps the FAILURE as
-- carefully as the success.
CREATE TABLE IF NOT EXISTS automation_runs (
    id             text        PRIMARY KEY DEFAULT gen_random_uuid()::text,
    workspace_id   text        NOT NULL,
    agent_id       text        NOT NULL,
    -- manual | mcp — who asked. Worth keeping: "why did this browser open my
    -- mail at 4am" is a question the run record has to answer.
    trigger        text        NOT NULL DEFAULT 'manual',
    -- users.id, or empty when a token asked. Never joined from the app pool —
    -- the app role has no grant on users at all.
    requested_by   text        NOT NULL DEFAULT '',
    -- The steps as submitted, verbatim JSON. Stored as given so a run reads
    -- back as it was asked for, not as we would ask for it now.
    params         jsonb       NOT NULL DEFAULT '{}'::jsonb,
    -- queued | running | ok | failed | cancelled
    status         text        NOT NULL DEFAULT 'queued',
    error          text        NOT NULL DEFAULT '',
    step_count     integer     NOT NULL DEFAULT 0,
    ok_count       integer     NOT NULL DEFAULT 0,
    started_at     timestamptz,
    finished_at    timestamptz,
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now(),
    UNIQUE (workspace_id, id)
);

CREATE INDEX IF NOT EXISTS automation_runs_workspace_idx ON automation_runs (workspace_id, created_at DESC);
CREATE INDEX IF NOT EXISTS automation_runs_agent_idx ON automation_runs (workspace_id, agent_id, created_at DESC);
-- "Is this browser busy" is asked before every run, and is the guardrail that
-- keeps one browser from being driven twice at once.
CREATE INDEX IF NOT EXISTS automation_runs_live_idx ON automation_runs (workspace_id, agent_id, status)
    WHERE status IN ('queued', 'running');

CREATE TABLE IF NOT EXISTS automation_run_steps (
    id              text        PRIMARY KEY DEFAULT gen_random_uuid()::text,
    workspace_id    text        NOT NULL,
    run_id          text        NOT NULL,
    -- "position", not "index": index is reserved in enough dialects to be worth
    -- avoiding.
    position        integer     NOT NULL DEFAULT 0,
    command         text        NOT NULL DEFAULT '',
    args            jsonb       NOT NULL DEFAULT '{}'::jsonb,
    -- pending | ok | failed | skipped
    status          text        NOT NULL DEFAULT 'pending',
    -- A short line for the list view. The full payload is in result.
    summary         text        NOT NULL DEFAULT '',
    -- What the browser sent back, stored as it arrived. A JSON round trip
    -- through a Go map reorders keys and renders numbers differently — the kind
    -- of quiet difference that makes a model's answer unreproducible.
    result          text        NOT NULL DEFAULT '',
    error           text        NOT NULL DEFAULT '',
    duration_ms     integer     NOT NULL DEFAULT 0,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now(),
    UNIQUE (workspace_id, id),
    UNIQUE (workspace_id, run_id, position)
);

CREATE INDEX IF NOT EXISTS automation_run_steps_run_idx ON automation_run_steps (workspace_id, run_id, position);

-- The kill switch, one row per workspace. Its absence means "not paused", so a
-- workspace that has never touched automation needs no row.
CREATE TABLE IF NOT EXISTS automation_settings (
    workspace_id text        PRIMARY KEY,
    paused       boolean     NOT NULL DEFAULT false,
    paused_at    timestamptz,
    paused_by    text        NOT NULL DEFAULT '',
    reason       text        NOT NULL DEFAULT '',
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now()
);
